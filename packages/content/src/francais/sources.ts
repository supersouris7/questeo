/** Page de conjugaison d'un verbe (morphologie), publiée par le CNRTL. `id` : le verbe sans accent. */
const conjugaison = (verbe: string): Source => {
  const id = verbe.replace(/[éèêç]/g, (c) => (c === 'ç' ? 'c' : 'e'));
  return {
    id: `cnrtl-conj-${id}`,
    title: `Conjugaison du verbe « ${verbe} » (portail lexical, morphologie)`,
    publisher: 'CNRTL (CNRS, ATILF)',
    url: `https://www.cnrtl.fr/morphologie/${encodeURIComponent(verbe)}/verbe`,
    textDate: '2026',
    consultedOn: '2026-11-25',
  };
};

